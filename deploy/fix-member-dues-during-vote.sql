-- ═══════════════════════════════════════════════════════════════════
--  投票進行中：調整個別會員的「2026 年會費繳納狀態」
-- ═══════════════════════════════════════════════════════════════════
--
--  為什麼需要這份腳本：
--    app/routers/members.py 的 _ensure_editable() 在人只要有一輪
--    status=active 時，會擋掉「所有」會員資料的修改（409
--    「投票進行中，無法修改會員名單」）。這個鎖是為了防止投票期間
--    增刪會員、改分會、改卡號 —— 那些會影響選舉公平性。
--    但「補繳會費」是行政作業，不是改選舉名單本身。
--
--  這份腳本只做三件事：
--    1. 只改 paid_2026_dues 這一個欄位（不碰姓名、卡號、分會、啟用狀態）
--    2. 寫入 activity_logs 稽核記錄（誰、什麼時候、改了哪些人）
--    3. 在同一個交易裡完成，出錯就整批回滾
--
--  影響面（已確認）：
--    paid_2026_dues 只在 vote_service.confirm_identity() 被讀一次，
--    沒有快取。改完之後該會員下一次「驗證身分」就會通過，不需重啟服務。
--    已投出的票完全不受影響。
--
--  用法：
--    在 NAS 的 fgs-db 容器終端機裡執行
--      psql -U fgs_app -d fgs_vote
--    然後把下面【第 ① 步】到【第 ③ 步】整段貼進去。
-- ═══════════════════════════════════════════════════════════════════


-- ┌─────────────────────────────────────────────────────────────────┐
-- │ ① 先確認對象（只查詢，不改任何東西）                            │
-- │    ↓↓↓ 把下面的卡號換成實際要處理的那幾位 ↓↓↓                    │
-- └─────────────────────────────────────────────────────────────────┘
SELECT member_no,
       name_trad          AS 姓名,
       division_id        AS 分會,
       paid_2026_dues     AS 目前是否已繳,
       is_active          AS 帳號啟用
FROM members
WHERE member_no IN (
    'B00000000000001',      -- ← 換成實際卡號
    'B00000000000002'       -- ← 換成實際卡號（數量不限，逗號分隔）
)
ORDER BY member_no;

-- 檢查重點：
--   1. 姓名與卡號對不對（同名同姓的情況很多，務必核對分會）
--   2. 目前是否已繳 = f（如果已經是 t，就不用處理）
--   3. 帳號啟用 = t（若為 f，改了也不會過，要另外處理）


-- ┌─────────────────────────────────────────────────────────────────┐
-- │ ② 改成已繳 + 寫入稽核記錄（同一個交易）                         │
-- └─────────────────────────────────────────────────────────────────┘
BEGIN;

UPDATE members
SET paid_2026_dues = true
WHERE member_no IN (
    'B00000000000001',      -- ← 與第 ① 步同一份名單
    'B00000000000002'
)
  AND paid_2026_dues = false;   -- 已經是 true 的不重複改

-- 稽核記錄（詳細名單寫進 detail，方便日後追溯）
INSERT INTO activity_logs (action, detail, operator, round_id)
SELECT '投票期間調整繳費狀態',
       'member_no=' || string_agg(member_no, ', ' ORDER BY member_no)
         || '；經選務確認後補登',
       'admin',
       (SELECT id FROM rounds WHERE status = 'active' ORDER BY id DESC LIMIT 1)
FROM members
WHERE member_no IN (
    'B00000000000001',
    'B00000000000002'
);

-- 確認無誤再提交；有疑慮就把 COMMIT 改成 ROLLBACK
COMMIT;


-- ┌─────────────────────────────────────────────────────────────────┐
-- │ ③ 確認結果                                                      │
-- └─────────────────────────────────────────────────────────────────┘
SELECT member_no, name_trad AS 姓名, paid_2026_dues AS 是否已繳
FROM members
WHERE member_no IN (
    'B00000000000001',
    'B00000000000002'
)
ORDER BY member_no;

-- 順便看一下有沒有寫進稽核記錄
SELECT created_at, action, detail, operator
FROM activity_logs
WHERE action = '投票期間調整繳費狀態'
ORDER BY id DESC
LIMIT 5;


