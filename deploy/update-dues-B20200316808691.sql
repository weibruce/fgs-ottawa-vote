-- ┌─────────────────────────────────────────────────────────────────┐
-- │ ① 先確認對象（只查詢，不改資料）                                │
-- └─────────────────────────────────────────────────────────────────┘
-- 預期結果 1 列：林秀洙 / 西區分會 / 目前已繳 = f / 啟用 = t
SELECT m.member_no,
       m.name_trad,
       d.name             AS 分會,
       m.paid_2026_dues   AS 目前已繳,
       m.is_active        AS 啟用
FROM members m
LEFT JOIN divisions d ON d.id = m.division_id
WHERE m.member_no = 'B20200316808691';

-- 若「目前已繳」已經是 t → 不用再跑下面，直接結束
-- 若查不到任何列 → 卡號打錯，先確認再繼續


-- ┌─────────────────────────────────────────────────────────────────┐
-- │ ② 改成已繳 + 寫入稽核（同一個交易）                             │
-- └─────────────────────────────────────────────────────────────────┘
-- 執行後看訊息：
--   INSERT 0 1  → 成功，改了一位
--   INSERT 0 0  → 卡號或姓名不符，什麼都沒改（請回第 ① 步檢查）
BEGIN;

WITH upd AS (
    UPDATE members
    SET paid_2026_dues = true
    WHERE member_no    = 'B20200316808691'
      AND name_trad    = '林秀洙'
      AND paid_2026_dues = false
    RETURNING member_no, name_trad
)
INSERT INTO activity_logs (action, detail, operator, round_id)
SELECT '投票期間調整繳費狀態',
       'member_no=' || member_no || ' ' || name_trad || '；經選務確認後補登',
       'admin',
       (SELECT id FROM rounds WHERE status = 'active' ORDER BY id DESC LIMIT 1)
FROM upd;

COMMIT;


-- ┌─────────────────────────────────────────────────────────────────┐
-- │ ③ 確認結果                                                      │
-- └─────────────────────────────────────────────────────────────────┘
-- 預期：paid_2026_dues = t
SELECT member_no, name_trad AS 姓名, paid_2026_dues AS 是否已繳
FROM members
WHERE member_no = 'B20200316808691';

-- 順便確認稽核記錄有寫進去
SELECT created_at, action, detail, operator
FROM activity_logs
WHERE action = '投票期間調整繳費狀態'
ORDER BY id DESC
LIMIT 3;


