--
--  已在開發資料庫以交易實測（rollback），確認：
--    · 更新 1 列、稽核寫入 1 列
--    · 重複執行不會重複寫稽核（idempotent）
--    · 姓名不符時完全不會改（保險機制）
--
--  這份只會動 paid_2026_dues 一個欄位，不碰姓名／卡號／分會／啟用狀態。
